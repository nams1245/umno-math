SUPERHARD_TASKS = []

def add(n, title, statements, solutions, kind='geometry', diagram=None):
    assert len(statements) == len(solutions) == 2
    for i, (q, s) in enumerate(zip(statements, solutions), 1):
        key=f'{n}sh{len([t for t in SUPERHARD_TASKS if t[1]==n])+1:02d}'
        criteria='2 балла: математически верный и полный ход решения с объяснением ключевых переходов. 1 балл: правильный метод с несущественной вычислительной ошибкой. 0 баллов: неверная идея или отсутствие обоснования. Это учебная схема, не официальный критерий ФИПИ.'
        SUPERHARD_TASKS.append((key,n,title,q,s,criteria,kind,'очень сложный'))

