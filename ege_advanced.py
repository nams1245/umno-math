assert len(LOOKUP)==len(TASKS)

def same_answer(given, expected):
    s=str(given).strip().replace(' ','').replace(',','.')
    try:
        return abs(float(s)-float(expected))<1e-8
    except (ValueError, OverflowError):
        return False

@bp.get('/ege/advanced')
def index():
    num=request.args.get('number',type=int)
    if num is not None and num not in range(1,20): abort(404)
    selected=[t for t in TASKS if num is None or t['num']==num]
    return render_template('ege_advanced_index.html', tasks=selected, selected=num, total=len(TASKS))

@bp.route('/ege/advanced/<key>',methods=['GET','POST'])
def detail(key):
    task=LOOKUP.get(key)
    if task is None: abort(404)
    text=''; evaluated=None; reveal=False
    if request.method=='POST':
        text=request.form.get('answer','')[:6000]
        if task['answer'] is not None:
            evaluated=same_answer(text,task['answer'])
            reveal=True
        else:
            reveal=request.form.get('action')=='reveal' and bool(text.strip())
    return render_template('ege_advanced_task.html', task=task, entered=text, evaluated=evaluated, reveal=reveal)

